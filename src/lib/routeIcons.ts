/**
 * The icon for a dashboard path: the nav entry whose href is the longest whole-segment prefix of the path
 * (`/dashboard/crm/leads/123` → Leads; `/dashboard/crm/leads/analytics` → Lead Analytics). The bare `/dashboard` entry
 * only matches `/dashboard` itself, so an unknown page gets no icon rather than the home one.
 */
export function iconNameForPath(pathname: string | null | undefined): NavIconName | null {
  if (!pathname) return null;
  const path = pathname.replace(/[?#].*$/, '').replace(/\/+$/, '') || '/';
  let best: { href: string; icon: NavIconName } | null = null;
  for (const [href, icon] of ROUTE_ICONS) {
    const hit = href === '/dashboard' ? path === href : path === href || path.startsWith(`${href}/`);
    if (hit && (!best || href.length > best.href.length)) best = { href, icon };
  }
  return best?.icon ?? null;
}
